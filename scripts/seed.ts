async function main() {
  for (const category of seedCategories) {
    await db
      .insert(categories)
      .values(category)
      .onConflictDoUpdate({
        target: categories.slug,
        set: { ...category, updatedAt: new Date() },
      });
  }

  for (const product of seedProducts) {
    await db
      .insert(products)
      .values(product)
      .onConflictDoUpdate({
        target: products.legacyId,
        set: { ...product, updatedAt: new Date() },
      });
  }

  console.log(
    `Seed terminé: ${seedCategories.length} catégories, ${seedProducts.length} produits.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
